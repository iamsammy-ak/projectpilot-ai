function ListEditor({ label, items, onChange }: { label: string; items: string[]; onChange: (next: string[]) => void }) {
  return (
    <section>
      <h3 className="mb-1 text-[13px] font-semibold text-ink-900">{label}</h3>
      <ul>
        {items.map((item, i) => (
          <li key={`${i}-${item}`} className="group flex items-start gap-1.5">
            <span className="mt-[13px] h-1 w-1 shrink-0 rounded-full bg-ink-300" />
            <InlineText multiline value={item} onCommit={(v) => onChange(v ? items.map((x, j) => (j === i ? v : x)) : items.filter((_, j) => j !== i))} />
            <IconButton label="Remove" className="mt-0.5 opacity-0 group-focus-within:opacity-100 group-hover:opacity-100" onClick={() => onChange(items.filter((_, j) => j !== i))}>
              <X size={13} />
            </IconButton>
          </li>
        ))}
      </ul>
      <button type="button" onClick={() => onChange([...items, 'New item'])} className="mt-0.5 ml-2 flex items-center gap-1 rounded-md px-1.5 py-1 text-xs font-medium text-brand-700 hover:bg-brand-50">
        <Plus size={12} /> Add
      </button>
    </section>
  )
}

