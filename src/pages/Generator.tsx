/* ───────────────────────────── Form ───────────────────────────── */

function PlanForm({ onGenerated }: { onGenerated: (id: string, notice: string | null) => void }) {
  const settings = useApp((s) => s.settings)
  const start0 = snapToWorkday(addDays(mondayOf(todayISO()), 7))
  const [name, setName] = useState('')
  const [description, setDescription] = useState('')
  const [type, setType] = useState<ProjectType>('software')
  const [start, setStart] = useState(start0)
  const [targetEnd, setTargetEnd] = useState(addDays(start0, 7 * 12 - 3))
  const [teamSize, setTeamSize] = useState(6)
  const [budget, setBudget] = useState('')
  const [complexity, setComplexity] = useState<Complexity>('medium')
  const [touched, setTouched] = useState(false)
  const [working, setWorking] = useState(false)
  const [step, setStep] = useState(0)

  const usingClaude = claudeEnabled(settings)
  const days = wIdxFloor(targetEnd) - wIdx(start) + 1
  const errors = {
    name: !name.trim() ? 'Give the project a name.' : '',
    dates: !start || !targetEnd ? 'Choose both dates.' : toDay(targetEnd) <= toDay(start) ? 'The target completion date must be after the start date.' : '',
    team: teamSize < 1 ? 'A project needs at least one person.' : '',
  }
  const invalid = !!(errors.name || errors.dates || errors.team)

  const run = async () => {
    setTouched(true)
    if (invalid || working) return
    const input: GeneratorInput = {
      name: name.trim(),
      description: description.trim(),
      type,
      start,
      targetEnd,
      teamSize,
      budget: budget.trim() ? Math.max(0, Number(budget)) : null,
      complexity,
    }
    setWorking(true)
    setStep(0)
    const began = Date.now()
    let current = 0
    // With Claude the first steps advance while the request is in flight and the rest when it returns.
    const timer = setInterval(() => {
      const cap = usingClaude ? 2 : STEPS.length - 1
      if (current < cap) setStep(++current)
    }, usingClaude ? 1400 : 330)

    let project: Project
    let notice: string | null = null
    try {
      if (usingClaude) {
        try {
          const outline = await claudeOutline(input, settings)
          project = buildProject(input, outline, { source: 'claude', fit: false })
          const a = analyze(project)
          if (a.eIdx > wIdxFloor(targetEnd)) {
            project = { ...project, planNotes: [...project.planNotes, `Claude’s estimates add up to a finish on ${fmtLong(a.end)}, after the target date. Shorten tasks in the WBS or move the target.`] }
          }
        } catch (e) {
          // Never present a failed request as a result: say what went wrong and which engine produced the plan.
          const reason = e instanceof AIError ? e.message : 'The request to Claude failed.'
          notice = `${reason} This plan was generated by the built-in planning engine instead.`
          project = generateWithEngine(input)
        }
      } else {
        if (settings.aiProvider === 'claude') notice = 'Claude is selected as the AI engine but no API key is set, so the built-in planning engine generated this plan. Add a key in Settings to use Claude.'
        project = generateWithEngine(input)
      }
      // Let each stage register on screen before showing the result.
      await new Promise((r) => setTimeout(r, Math.max(0, 1750 - (Date.now() - began))))
    } finally {
      clearInterval(timer)
    }
    setStep(STEPS.length)
    useApp.getState().addProject(project)
    onGenerated(project.id, notice)
  }

  if (working) {
    return (
      <Card className="mx-auto max-w-xl">
        <div className="px-7 py-8">
          <div className="mb-5 flex items-center gap-3">
            <span className="flex h-10 w-10 items-center justify-center rounded-xl bg-brand-600 text-white">
              <WandSparkles size={20} />
            </span>
            <div>
              <h2 className="text-base font-semibold text-ink-900">Generating your project plan</h2>
              <p className="text-[13px] text-ink-500">{usingClaude ? `Waiting for ${CLAUDE_MODELS.find((m) => m.id === settings.model)?.label.replace(/ \(.*\)$/, '') ?? 'Claude'}, then scheduling locally` : 'Built-in planning engine, running in your browser'}</p>
            </div>
          </div>
          <ol className="space-y-2.5" aria-live="polite">
            {STEPS.map((label, i) => (
              <li key={label} className={cx('flex items-center gap-3 text-sm transition-colors', i > step ? 'text-ink-400' : 'text-ink-900')}>
                <span className={cx('flex h-6 w-6 shrink-0 items-center justify-center rounded-full', i < step ? 'bg-emerald-100 text-emerald-700' : i === step ? 'bg-brand-100 text-brand-700' : 'bg-canvas text-ink-300')}>
                  {i < step ? <Check size={14} strokeWidth={3} /> : i === step ? <LoaderCircle size={14} className="animate-spin" /> : <span className="h-1.5 w-1.5 rounded-full bg-current" />}
                </span>
                {label}
              </li>
            ))}
          </ol>
        </div>
      </Card>
    )
  }

  return (
    <div className="grid items-start gap-5 xl:grid-cols-[minmax(0,1fr)_340px]">
      <Card>
        <form
          className="space-y-5 p-5 sm:p-6"
          onSubmit={(e) => {
            e.preventDefault()
            void run()
          }}
          noValidate
        >
          <Field label="Project name">
            <input className={inputCls} value={name} onChange={(e) => setName(e.target.value)} placeholder="e.g. Customer Self-Service Portal" autoFocus />
            {touched && errors.name && <p className="mt-1 text-xs text-red-600">{errors.name}</p>}
          </Field>
          <Field label="Project description" hint="What is being delivered, for whom, and why">
            <textarea className={textareaCls} rows={4} value={description} onChange={(e) => setDescription(e.target.value)} placeholder="Describe the outcome, the main features or deliverables, and any constraints the plan should respect." />
          </Field>

          <div className="grid gap-5 sm:grid-cols-2">
            <Field label="Project type">
              <select className={inputCls} value={type} onChange={(e) => setType(e.target.value as ProjectType)}>
                {(Object.keys(PROJECT_TYPE_LABEL) as ProjectType[]).map((t) => (
                  <option key={t} value={t}>
                    {PROJECT_TYPE_LABEL[t]}
                  </option>
                ))}
              </select>
            </Field>
            <Field label="Project complexity">
              <div className="grid grid-cols-3 gap-1.5">
                {(Object.keys(COMPLEXITY_LABEL) as Complexity[]).map((c) => (
                  <button
                    key={c}
                    type="button"
                    aria-pressed={complexity === c}
                    onClick={() => setComplexity(c)}
                    className={cx('h-9 rounded-lg border text-sm font-medium transition-colors', complexity === c ? 'border-brand-500 bg-brand-50 text-brand-700' : 'border-line bg-white text-ink-600 hover:border-ink-300')}
                  >
                    {COMPLEXITY_LABEL[c]}
                  </button>
                ))}
              </div>
            </Field>
            <Field label="Start date">
              <input type="date" className={cx(inputCls, 'tnum')} value={start} onChange={(e) => setStart(e.target.value)} />
            </Field>
            <Field label="Target completion date" hint={!errors.dates && days > 0 ? `${days} working days` : undefined}>
              <input type="date" className={cx(inputCls, 'tnum')} value={targetEnd} min={start} onChange={(e) => setTargetEnd(e.target.value)} />
              {touched && errors.dates && <p className="mt-1 text-xs text-red-600">{errors.dates}</p>}
            </Field>
            <Field label="Team size" hint="people">
              <input type="number" min={1} max={60} className={cx(inputCls, 'tnum')} value={teamSize} onChange={(e) => setTeamSize(Math.min(60, Math.round(Number(e.target.value))))} />
              {touched && errors.team && <p className="mt-1 text-xs text-red-600">{errors.team}</p>}
            </Field>
            <Field label="Budget" hint="optional, USD">
              <input type="number" min={0} step={1000} className={cx(inputCls, 'tnum')} value={budget} onChange={(e) => setBudget(e.target.value)} placeholder="No budget set" />
            </Field>
          </div>

          <div className="flex flex-wrap items-center gap-3 border-t border-line-soft pt-5">
            <button
              type="submit"
              className="inline-flex h-12 items-center gap-2.5 rounded-xl bg-gradient-to-r from-brand-600 to-azure-500 px-6 text-[15px] font-semibold text-white shadow-[0_8px_24px_-8px_rgb(98_56_245/0.7)] transition-[filter,transform] hover:brightness-110 active:scale-[0.99]"
            >
              <Sparkles size={18} />
              Generate Project Plan with AI
            </button>
            <Button
              variant="ghost"
              onClick={() => {
                setName(EXAMPLE.name)
                setDescription(EXAMPLE.description)
                setType(EXAMPLE.type)
                setTeamSize(EXAMPLE.teamSize)
                setBudget(EXAMPLE.budget)
                setComplexity(EXAMPLE.complexity)
              }}
            >
              Fill in an example
            </Button>
          </div>
        </form>
      </Card>

      <aside className="space-y-4">
        <Card>
          <div className="p-5">
            <h2 className="text-[15px] font-semibold text-ink-900">What the plan contains</h2>
            <ul className="mt-3 space-y-3 text-[13px]">
              {(
                [
                  [<FileText size={15} />, 'Project charter', 'Objective, justification, scope, deliverables, stakeholders, success criteria, assumptions and constraints'],
                  [<ListTree size={15} />, 'Work breakdown structure', 'Phases and tasks with WBS codes, durations, responsible roles, dependencies and milestones'],
                  [<CalendarRange size={15} />, 'Project schedule', 'Start and end dates computed from the dependency network and fitted to your target date'],
                  [<ShieldAlert size={15} />, 'Risk register', 'Risks scored by probability and impact, each with a mitigation strategy'],
                  [<Users size={15} />, 'Resource plan', 'Roles sized to your team, estimated workload and suggested allocation'],
                ] as [ReactNode, string, string][]
              ).map(([icon, title, body]) => (
                <li key={title} className="flex gap-2.5">
                  <span className="mt-0.5 shrink-0 text-brand-600">{icon}</span>
                  <span>
                    <span className="block font-medium text-ink-900">{title}</span>
                    <span className="text-ink-500">{body}</span>
                  </span>
                </li>
              ))}
            </ul>
          </div>
        </Card>
        <Card>
          <div className="p-5 text-[13px]">
            <h2 className="flex items-center gap-2 text-[15px] font-semibold text-ink-900">
              {usingClaude ? <Sparkles size={16} className="text-brand-600" /> : <Cpu size={16} className="text-azure-600" />}
              {usingClaude ? 'Claude API' : 'Built-in planning engine'}
            </h2>
            <p className="mt-1.5 text-ink-500">
              {usingClaude
                ? 'Claude drafts the charter, WBS and risks from your description. Dates and dependencies are then scheduled locally. If the request fails, you are told and the built-in engine is used.'
                : 'Plans are built in your browser from a library of project-type templates, then scheduled and sized to your dates, team and complexity. No data leaves this device.'}
            </p>
            <button type="button" onClick={() => navigate('settings')} className="mt-2.5 font-medium text-brand-700 hover:underline">
              {usingClaude ? 'Change AI engine' : 'Connect the Claude API'}
            </button>
          </div>
        </Card>
      </aside>
    </div>
  )
}

